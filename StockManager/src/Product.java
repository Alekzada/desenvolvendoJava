public class Product {
    public String name;
    public String brand;
    public String category;
    public Float weight;
    public Float price;

    Product(
        String name,
        String brand,
        String category,
        Float weight,
        Float price
    ) {
        this.name = name;
        this.brand = brand;
        this.category = category;
        this.weight = weight;
        this.price = price;
    }
}
